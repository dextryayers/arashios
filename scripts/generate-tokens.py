    for key, value in tokens["typography"]["weight"].items():
        lines.append(f"  --kage-weight-{kebab(key)}: {value};")
    for key, value in tokens["typography"]["letterSpacing"].items():
        lines.append(f"  --kage-letter-spacing-{kebab(key)}: {value};")
    lines += ["", "  /* Space */"]
